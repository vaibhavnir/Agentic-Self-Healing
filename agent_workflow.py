# ---------------------------------------------------------------------------
# Routing logic
# ---------------------------------------------------------------------------

def route_after_qa(state: DatabricksPipelineState) -> str:
    """Conditional edge: route to 'deploy' on QA pass, 'rewrite' on failure.

    The ``"rewrite"`` branch loops back to ``engineer_agent`` so the engineer
    can produce an explicit ``ALTER TABLE`` fix after the QA Agent rejects the
    initial ``mergeSchema`` approach.

    Parameters
    ----------
    state:
        Current pipeline state.  Reads ``qa_passed``.

    Returns
    -------
    str
        ``"deploy"`` or ``"rewrite"``.
    """
    if state.get("qa_passed"):
        return "deploy"
    return "rewrite"


# ---------------------------------------------------------------------------
# Graph compilation
# ---------------------------------------------------------------------------

def build_graph() -> StateGraph:
    """Compile and return the LangGraph StateGraph for the healing workflow.

    Graph topology::

        START → detective → engineer → qa ─(pass)─→ deploy → END
                                ↑          │
                                └──(fail)───┘

    Returns
    -------
    StateGraph
        A compiled, runnable LangGraph graph.
    """
    graph = StateGraph(DatabricksPipelineState)

    graph.add_node("detective", detective_agent)
    graph.add_node("engineer", engineer_agent)
    graph.add_node("qa", qa_agent)
    graph.add_node("deploy", deployment_agent)

    graph.add_edge(START, "detective")
    graph.add_edge("detective", "engineer")
    graph.add_edge("engineer", "qa")

    graph.add_conditional_edges(
        "qa",
        route_after_qa,
        {"deploy": "deploy", "rewrite": "engineer"},
    )

    graph.add_edge("deploy", END)

    return graph.compile()


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------

async def run_healing_workflow(job_id: str, error_logs: str) -> dict:
    """Run the full self-healing workflow for a failed Databricks job.

    Parameters
    ----------
    job_id:
        The Databricks job ID that triggered the failure alert.
    error_logs:
        Raw log text from the failed job run (used by the Detective Agent).

    Returns
    -------
    dict
        Final ``DatabricksPipelineState`` after all agents have completed.
    """
    app = build_graph()

    initial_state: DatabricksPipelineState = {
        "job_id": job_id,
        "error_logs": error_logs,
        "drift_details": "",
        "proposed_sql_fix": "",
        "proposed_pyspark_fix": "",
        "fix_strategy": "",
        "qa_passed": False,
        "qa_feedback": "",
        "status_message": "",
    }

    print(f"\n{'='*60}")
    print(f" Self-Healing Workflow started for job: {job_id}")
    print(f"{'='*60}\n")

    final_state = await app.ainvoke(initial_state)

    print(f"\n{'='*60}")
    print(f" Workflow complete. Status: {final_state['status_message']}")
    print(f"{'='*60}\n")

    return final_state


