async def engineer_agent(state: DatabricksPipelineState) -> dict:
    """Formulate a Delta Lake schema evolution strategy to fix the drift.

    On the **first pass** the engineer proposes the least-invasive fix:
    enabling ``mergeSchema`` on the PySpark write so Delta Lake absorbs the
    new column automatically.

    If the QA Agent rejects that approach (e.g. because data-governance policy
    forbids implicit schema evolution), the engineer escalates to an explicit
    ``ALTER TABLE`` DDL that gives full control over the change.

    Parameters
    ----------
    state:
        Current pipeline state.  Reads ``drift_details``, ``qa_passed``, and
        ``qa_feedback`` to decide which strategy to apply.

    Returns
    -------
    dict
        ``{"proposed_sql_fix": <str>, "proposed_pyspark_fix": <str>}``
    """
    print(
        f"[{state['job_id']}] 🛠️  Engineer: "
        "Formulating Delta Lake schema evolution strategy..."
    )

    await asyncio.sleep(1)

    # Second attempt: QA rejected mergeSchema — use explicit DDL instead.
    if state.get("qa_feedback") and not state.get("qa_passed", False):
        sql_fix = "ALTER TABLE main.sales.customers ADD COLUMN loyalty_tier STRING;"
        pyspark_fix = (
            "No changes to PySpark write needed; "
            "schema explicitly evolved via ALTER TABLE."
        )
        fix_strategy = "alter_table"
    else:
        # First attempt: let Delta Lake handle the new column automatically.
        sql_fix = "None"
        pyspark_fix = (
            'df.write.format("delta")\n'
            '  .mode("append")\n'
            '  .option("mergeSchema", "true")\n'
            '  .saveAsTable("main.sales.customers")'
        )
        fix_strategy = "merge_schema"

    return {
        "proposed_sql_fix": sql_fix,
        "proposed_pyspark_fix": pyspark_fix,
        "fix_strategy": fix_strategy,
    }


async def qa_agent(state: DatabricksPipelineState) -> dict:
    """Validate the proposed fix using a Zero-Copy Clone of the Delta table.

    This agent enforces enterprise data-governance policies before any change
    reaches production.  It performs the following steps in a real deployment:

    1. Creates an isolated sandbox clone::

           CREATE TABLE dev.sandbox.customers_clone
           CLONE main.sales.customers;

    2. Applies the Engineer's proposed PySpark or SQL fix against the clone.
    3. Runs a data-quality check (row counts, NULL rates, type assertions).
    4. Drops the clone when finished to free storage.

    A key governance rule modelled here: implicit ``mergeSchema=True`` is
    **rejected** because it could silently absorb upstream garbage columns.
    All schema changes must be declared through explicit ``ALTER TABLE`` DDL.

    Parameters
    ----------
    state:
        Current pipeline state.  Reads ``job_id``, ``proposed_pyspark_fix``,
        and ``proposed_sql_fix``.

    Returns
    -------
    dict
        ``{"qa_passed": bool, "qa_feedback": str}``
    """
    print(f"[{state['job_id']}] 🧪  QA: Cloning Delta table and testing fix...")

    # --- Production replacement -------------------------------------------
    # await mcp_databricks.run_sql(
    #     "CREATE TABLE dev.sandbox.customers_clone CLONE main.sales.customers"
    # )
    # await mcp_databricks.run_pyspark(state["proposed_pyspark_fix"], target="clone")
    # quality_ok = await run_data_quality_checks("dev.sandbox.customers_clone")
    # await mcp_databricks.run_sql("DROP TABLE dev.sandbox.customers_clone")
    # ----------------------------------------------------------------------

    await asyncio.sleep(1)

