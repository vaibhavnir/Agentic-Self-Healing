"""
agent_workflow.py
-----------------
LangGraph-based Agentic Self-Healing workflow for Databricks schema drift.

This module defines a four-agent pipeline that automatically detects, diagnoses,
tests, and fixes schema drift failures in Databricks Delta Lake tables:

    Detective  →  Engineer  →  QA ──(pass)──→  Deploy
                     ↑                |
                     └───(fail/rewrite)┘

Agents
------
1. detective_agent  – Queries Unity Catalog to identify the exact columns that
                      drifted (new column, type change, or dropped field).
2. engineer_agent   – Proposes a fix: either a PySpark `mergeSchema` option or
                      an explicit `ALTER TABLE` DDL, depending on QA feedback.
3. qa_agent         – Spins up a Zero-Copy Clone of the production Delta table
                      and validates the proposed fix in an isolated sandbox.
4. deployment_agent – Applies the approved fix to production via the Unity
                      Catalog REST API and restarts the failed Databricks job.

Usage
-----
Invoke the compiled graph directly::

    asyncio.run(run_healing_workflow(job_id="12345", error_logs="..."))

Or trigger it through the FastAPI webhook in ``api.py``.
"""

import asyncio
from typing import TypedDict

from langgraph.graph import StateGraph, START, END


# ---------------------------------------------------------------------------
# State definition
# ---------------------------------------------------------------------------

class DatabricksPipelineState(TypedDict):
    """Shared state passed between every agent node in the graph.

    Attributes
    ----------
    job_id:
        The Databricks Jobs API job identifier that failed.
    error_logs:
        Raw log output captured from the failed job run, typically containing
        a Spark ``AnalysisException`` with schema mismatch details.
    drift_details:
        Human-readable summary of the detected schema drift produced by the
        Detective Agent (e.g. "new column 'loyalty_tier' (StringType) added").
    proposed_sql_fix:
        DDL statement (e.g. ``ALTER TABLE … ADD COLUMN …``) generated by the
        Engineer Agent, or ``"None"`` when no DDL change is needed.
    proposed_pyspark_fix:
        Updated PySpark write code generated by the Engineer Agent, or a
        descriptive string when no PySpark change is required.
    qa_passed:
        ``True`` if the QA Agent approved the proposed fix on the cloned table,
        ``False`` otherwise.
    qa_feedback:
        Plain-text explanation returned by the QA Agent describing why the fix
        passed or failed governance checks.
    fix_strategy:
        Tracks the Engineer Agent's chosen fix strategy: ``"merge_schema"`` for
        the implicit Delta Lake option or ``"alter_table"`` for an explicit DDL.
        Used by the QA Agent to apply governance rules without brittle string
        matching on generated code.
    status_message:
        Final human-readable summary set by the Deploy Agent once the pipeline
        has been healed and the job restarted.
    """

    job_id: str
    error_logs: str
    drift_details: str
    proposed_sql_fix: str
    proposed_pyspark_fix: str
    fix_strategy: str  # "merge_schema" | "alter_table"
    qa_passed: bool
    qa_feedback: str
    status_message: str


